#!/bin/bash
# Lavoro di una volta sul Mac mini: lo lancia il server di Atlante Musica all'avvio (vedi «Lavori di una volta» in
# musica_libreria.py), dopo che l'aggiornamento automatico l'ha portato qui.
#
# Toglie il codice a 6 cifre dalla schermata di accesso di Atlante Accessi, il «Controllo remoto» (lo schermo dei Mac
# dal browser, porta pubblica 8443): restano utente e password di Accessi, poi la password del Mac. Chiesto da Samuele
# il 20/11/2026. Il codice di Accessi è solo su questo Mac, non nel repo: la modifica la fa Claude Code installato qui,
# senza nessuno davanti (claude -p), che trova Accessi, lo legge, lo cambia, lo riavvia e controlla.
# Uscita 0 solo se Claude chiude con la riga ESITO: OK; altrimenti il server riprova ai prossimi avvii (al più 3 volte).
# Quello che succede: ~/Atlante/una_volta/accessi_senza_codice.txt e una riga in ~/Atlante/registro.log.
set -u
export PATH="$HOME/.local/bin:$HOME/.claude/local:/opt/homebrew/bin:/usr/local/bin:/usr/bin:/bin:/usr/sbin:/sbin:$PATH"
LOG="$HOME/Atlante/registro.log"
log() { echo "$(date '+%Y-%m-%d %H:%M:%S') accessi-senza-codice: $*" >> "$LOG"; echo "$*"; }

CLAUDE=""
for c in "$(command -v claude 2>/dev/null)" "$HOME/.local/bin/claude" "$HOME/.claude/local/claude" \
         /opt/homebrew/bin/claude /usr/local/bin/claude "$HOME/.npm-global/bin/claude"; do
  if [ -n "$c" ] && [ -x "$c" ]; then CLAUDE="$c"; break; fi
done
if [ -z "$CLAUDE" ]; then log "Claude Code non è installato su questo Mac: Accessi resta com'è"; exit 1; fi

# read e non $(cat <<…): il bash 3.2 del Mac, dentro $(…), conta gli apostrofi del testo e si confonde
IFS= read -r -d '' COMPITO <<'FINE' || true
Sei sul Mac mini di Samuele e lavori senza nessuno davanti: nessuno risponde alle domande, decidi da solo e con prudenza.

COMPITO: in Atlante Accessi (il «Controllo remoto»: lo schermo dei Mac dal browser, pubblicato da Tailscale Funnel sulla porta 8443 di questo Mac) togli il codice a 6 cifre dalla schermata di accesso. Dopo la modifica per entrare bastano utente e password di Accessi, poi, come adesso, la password del Mac per lo schermo. Samuele l'ha chiesto esplicitamente il 20/11/2026.

1. Trova Accessi. Non è Atlante Musica: ~/Atlante/musica e ~/Atlante/repo NON sono Accessi. Strade: `/Applications/Tailscale.app/Contents/MacOS/Tailscale serve status` (o `tailscale serve status`) dice a quale porta locale va la 8443; `lsof -nP -iTCP:<porta> -sTCP:LISTEN` dà il processo; `ps -o command= -p <pid>` e `lsof -a -p <pid> -d cwd` dicono quale programma e in quale cartella; i LaunchAgent in ~/Library/LaunchAgents (cerca «accessi») dicono come parte e come si riavvia. Probabilmente è dentro ~/Atlante.
2. Prima di cambiare qualcosa guarda se il codice è già stato tolto (un tentativo di prima): allora controlla soltanto (punto 5).
3. Leggi come funziona l'accesso: dove il server controlla il codice (TOTP o simile) e dove la pagina lo chiede.
4. Prima di cambiare un file fanne una copia accanto con il suffisso .prima-senza-codice. Poi togli il codice: il server non deve più chiederlo né controllarlo (non basta nascondere il campo) e la pagina di accesso non deve più mostrarlo. Se Accessi ha già un'impostazione per spegnerlo, usa quella. Lascia tutto il resto com'è: utente e password, il limite ai tentativi sbagliati e le attese, cookie e sessioni, «Persone», la password del Mac. Non cancellare i segreti del codice già salvati, così si può riaccendere. Aggiorna i testi di Accessi che parlano del codice. Se Accessi ha delle prove, aggiornale e falle girare.
5. Riavvia Accessi (`launchctl kickstart -k gui/$(id -u)/<etichetta del suo LaunchAgent>`) e controlla con curl sulla sua porta locale che la pagina di accesso risponda e non chieda più il codice, e che un accesso con una password sbagliata sia ancora rifiutato.
6. Se qualcosa va storto e non riesci a sistemarlo, rimetti le copie .prima-senza-codice, riavvia Accessi e controlla che funzioni come prima.
7. Se `gh auth status` dice che gh è collegato a GitHub, lascia un commento breve in italiano sulla PR 79 di samuelemanfredi/atlante (`gh pr comment 79 --repo samuelemanfredi/atlante --body "..."`) con l'esito: quali file hai cambiato e cosa hai controllato. Niente password, segreti, codici o indirizzi completi nel commento. Chiudi il commento con queste due righe:
---
_Generated by [Claude Code](https://claude.ai/code)_

Ultima riga della risposta, da sola e senza altri segni: ESITO: OK se il codice non è più chiesto e Accessi funziona; altrimenti ESITO: NON FATTO seguito dal motivo.
FINE

# comandi permessi senza chiedere (nessuno può rispondere): niente sudo, niente rm
STRUMENTI="Read,Edit,Write,Glob,Grep,Bash(lsof:*),Bash(ps:*),Bash(launchctl:*),Bash(tailscale:*)"
STRUMENTI="$STRUMENTI,Bash(/Applications/Tailscale.app/Contents/MacOS/Tailscale:*),Bash(cp:*),Bash(curl:*),Bash(grep:*)"
STRUMENTI="$STRUMENTI,Bash(ls:*),Bash(cat:*),Bash(head:*),Bash(tail:*),Bash(find:*),Bash(diff:*),Bash(plutil:*),Bash(id:*)"
STRUMENTI="$STRUMENTI,Bash(python3:*),Bash(node:*),Bash(npm:*),Bash(sqlite3:*),Bash(git:*),Bash(gh:*),Bash(sleep:*)"

cd "$HOME/Atlante" 2>/dev/null || cd "$HOME" || exit 1
USCITA=$(mktemp -t accessi-senza-codice) || exit 1
trap 'rm -f "$USCITA"' EXIT
log "comincio con $CLAUDE"
"$CLAUDE" -p "$COMPITO" --permission-mode acceptEdits --add-dir "$HOME" --allowedTools "$STRUMENTI" >"$USCITA" 2>&1 </dev/null &
PID=$!
( sleep 5400; kill "$PID" 2>/dev/null ) &   # al più un'ora e mezza: poi si riprova al prossimo avvio
CANE=$!
wait "$PID"
R=$?
kill "$CANE" 2>/dev/null
cat "$USCITA"
if [ "$R" -eq 0 ] && tail -5 "$USCITA" | grep -q 'ESITO: OK'; then
  log "fatto: Accessi non chiede più il codice a 6 cifre"
  exit 0
fi
log "non fatto (uscita $R): $(grep 'ESITO:' "$USCITA" | tail -1 | cut -c1-300)"
exit 1
